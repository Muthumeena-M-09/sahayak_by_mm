export function localizeServiceTemplates(
  templates: ServiceTemplate[],
  uiDict: Record<string, string>,
  langCode: string
): ServiceTemplate[] {
  if (!langCode || langCode === 'en') return templates;
  const termMap = SERVICE_TERM_TRANSLATIONS[langCode] || {};
  const trTerm = (raw: string) => uiDict[`svc_term.${raw}`] || termMap[raw] || raw;

  return templates.map((tpl) => {
    const titleKey = `svc.${tpl.slug}.title`;
    const descKey = `svc.${tpl.slug}.desc`;
    return {
      ...tpl,
      title: uiDict[titleKey] || tpl.title,
      description: uiDict[descKey] || tpl.description,
      requiredDocuments: (tpl.requiredDocuments || []).map(trTerm),
      formSchema: (tpl.formSchema || []).map((field) => ({
        ...field,
        label: trTerm(field.label),
        options: field.options ? field.options.map(trTerm) : undefined,
      })),
    };
  });
}
